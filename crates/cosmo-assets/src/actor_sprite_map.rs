//! Maps each `ACT_*` actor type (map_type - 31) to the `SPR_*` sprite type
//! actually used to render it. These are two different numbering spaces
//! that only sometimes coincide - actor.h's header comment says so
//! explicitly: "These are _not_ the sprite numbers as used in the group
//! entry file (although in many cases the actor and sprite type numbers
//! have some amount of coorelation)."
//!
//! Extracted directly from every `case ACT_X: ConstructActor(SPR_Y, ...)`
//! arm of `NewActorAtIndex()`, game1.c:5618-6371 (the switch body itself is
//! 5626-6365). Every `ACT_*` id defined in actor.h has a case here except
//! `SPA_*` (map types 0..8, not real actors) - confirmed by cross-checking
//! every enum value in actor.h against a `case` label; the only gaps are
//! actor.h's own unused numeric holes (ids that were never assigned a
//! `#define` at all), not missing switch arms.
//!
//! A handful of actors use "numbered" sprite slots (`SPR_150`, `SPR_164`,
//! `SPR_248`, `SPR_249`, `SPR_250`, `SPR_265`) that sprite.h documents as
//! "copy of X; never shown" - these are invisible trigger/marker actors
//! (exit lines, episode-end triggers, smoke emitters) whose graphic slot
//! is a leftover duplicate the original never actually draws. They're
//! included here for completeness with real numeric values, not omitted.

