/// Looks up the `SPR_*` sprite id for a given `ACT_*` id, if known.
pub fn sprite_for_actor(act_id: u16) -> Option<u16> {
    ACT_TO_SPRITE
        .iter()
        .find(|(a, _, _, _)| *a == act_id)
        .map(|(_, s, _, _)| *s)
}

/// Looks up what a container actor spawns when broken, if it is one.
pub fn container_contents(act_id: u16) -> Option<u16> {
    CONTAINER_CONTENTS
        .iter()
        .find(|(c, _, _, _)| *c == act_id)
        .map(|(_, contents, _, _)| *contents)
}
